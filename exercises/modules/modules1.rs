mod sausage_factory {
    // Don't let anybody outside of this module see this!
    fn get_secret_recipe() -> String {
        String::from("Ginger")
    }

    // main() lives outside this module, so the entry point has to be exported.
    // get_secret_recipe() stays private on purpose: the comment above says so,
    // and make_sausage() can still reach it because it is in the same module.
    pub fn make_sausage() {
        get_secret_recipe();
        println!("sausage!");
    }
}

fn main() {
    sausage_factory::make_sausage();
}
